/// A registered printer, including the credentials used to reach it.
///
/// Not `Debug` on purpose, so the password cannot end up in logs.
#[derive(Clone)]
pub struct StoredPrinter {
    pub name: String,
    pub kind: PrinterKind,
    pub host: String,
    pub username: String,
    pub password: String,
}

impl StoredPrinter {
    pub fn summary(&self) -> PrinterSummary {
        PrinterSummary {
            name: self.name.clone(),
            kind: self.kind,
            host: self.host.clone(),
            username: self.username.clone(),
        }
    }

    pub fn client(&self, http: reqwest::Client) -> PrusaLinkClient {
        PrusaLinkClient::new(http, &self.host, &self.username, &self.password)
    }
}

#[derive(Debug, thiserror::Error)]
pub enum StoreError {
    #[error("printer `{0}` already exists")]
    Duplicate(String),
    /// Deliberately carries no URL text: it may contain credentials.
    #[error("{0}")]
    InvalidDatabaseUrl(String),
    #[error("database schema version {found} is newer than this binary supports ({supported})")]
    IncompatibleSchema { found: i32, supported: i32 },
    #[error("STARSTAR_LIBRARY_DIR: {0}")]
    LibraryIo(#[from] std::io::Error),
    #[error("database error: {0}")]
    Database(#[from] sqlx::Error),
}

/// Returns true if `err` is a PostgreSQL `unique_violation` (`23505`).
pub(crate) fn is_unique_violation(err: &sqlx::Error) -> bool {
    err.as_database_error()
        .and_then(|db| db.code())
        .is_some_and(|code| code == "23505")
}

