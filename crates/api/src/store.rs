pub(crate) async fn run_migrations(
    pool: &PgPool,
    migrations: &[Migration],
) -> Result<(), StoreError> {
    let mut tx = pool.begin().await?;
    sqlx::query("SET TRANSACTION ISOLATION LEVEL READ COMMITTED")
        .execute(&mut *tx)
        .await?;
    sqlx::query("SELECT pg_advisory_xact_lock($1, hashtext(current_schema()))")
        .bind(MIGRATION_LOCK_NS)
        .execute(&mut *tx)
        .await?;
    (&mut *tx)
        .execute(
            "CREATE TABLE IF NOT EXISTS schema_migrations (
                version    INTEGER PRIMARY KEY,
                name       TEXT NOT NULL,
                applied_at BIGINT NOT NULL
            )",
        )
        .await?;

    let current: i32 =
        sqlx::query_scalar("SELECT COALESCE(MAX(version), 0) FROM schema_migrations")
            .fetch_one(&mut *tx)
            .await?;
    let supported = migrations.last().map_or(0, |m| m.version);
    if current > supported {
        return Err(StoreError::IncompatibleSchema {
            found: current,
            supported,
        });
    }

    let now = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .unwrap_or_default()
        .as_secs() as i64;
    for m in migrations.iter().filter(|m| m.version > current) {
        (&mut *tx).execute(m.sql).await?;
        sqlx::query(
            "INSERT INTO schema_migrations (version, name, applied_at) VALUES ($1, $2, $3)",
        )
        .bind(m.version)
        .bind(m.name)
        .bind(now)
        .execute(&mut *tx)
        .await?;
    }
    tx.commit().await?;
    Ok(())
}

/// Options for opening a PostgreSQL pool.
#[derive(Clone, Debug)]
pub struct DbOptions {
    pub max_connections: u32,
    pub acquire_timeout: Duration,
    pub idle_timeout: Duration,
    pub connect_retry_timeout: Duration,
    pub schema: Option<String>,
}

impl Default for DbOptions {
    fn default() -> Self {
        Self {
            max_connections: 10,
            acquire_timeout: Duration::from_secs(5),
            idle_timeout: Duration::from_secs(300),
            connect_retry_timeout: Duration::ZERO,
            schema: None,
        }
    }
}

fn parse_connect_options(url: &str, schema: Option<&str>) -> Result<PgConnectOptions, StoreError> {
    let trimmed = url.trim();
    let parsed = Url::parse(trimmed).map_err(|_| {
        StoreError::InvalidDatabaseUrl(
            "database URL must be a valid postgres:// or postgresql:// URL".to_owned(),
        )
    })?;
    if !matches!(parsed.scheme(), "postgres" | "postgresql") || parsed.host_str().is_none() {
        return Err(StoreError::InvalidDatabaseUrl(
            "database URL must use postgres:// or postgresql:// with a host".to_owned(),
        ));
    }
    let mut opts = PgConnectOptions::from_str(trimmed).map_err(|_| {
        StoreError::InvalidDatabaseUrl("could not parse PostgreSQL connection options".to_owned())
    })?;
    if let Some(schema) = schema {
        opts = opts.options([("search_path", schema)]);
    }
    Ok(opts)
}

fn is_permanent_connect_error(err: &StoreError) -> bool {
    match err {
        StoreError::InvalidDatabaseUrl(_)
        | StoreError::IncompatibleSchema { .. }
        | StoreError::Duplicate(_)
        | StoreError::LibraryIo(_) => true,
        StoreError::Database(sqlx_err) => match sqlx_err {
            sqlx::Error::Configuration(_) => true,
            sqlx::Error::Database(db) => matches!(
                db.code().as_deref(),
                Some("28P01" | "28000" | "3D000" | "3F000")
            ),
            _ => false,
        },
    }
}

/// Shared PostgreSQL connection pool for the printer registry and auth tables.
///
/// Not `Debug`.
#[derive(Clone)]
pub struct Db {
    pool: PgPool,
    _test_cleanup: Option<Arc<test_db::TestSchemaGuard>>,
}

impl Db {
    /// Connects to PostgreSQL with a single attempt and runs pending migrations.
    pub async fn connect(url: &str, opts: DbOptions) -> Result<Self, StoreError> {
        Self::connect_inner(url, opts, None).await
    }

    /// Connects to PostgreSQL, retrying transient failures with exponential
    /// backoff up to `opts.connect_retry_timeout`, then runs pending migrations.
    pub async fn connect_with_retry(url: &str, opts: DbOptions) -> Result<Self, StoreError> {
        if opts.connect_retry_timeout.is_zero() {
            return Self::connect_inner(url, opts, None).await;
        }
        let deadline = Instant::now() + opts.connect_retry_timeout;
        let mut backoff = Duration::from_millis(250);
        let mut last_err = None;
        loop {
            let Some(remaining) = deadline.checked_duration_since(Instant::now()) else {
                return Err(last_err.unwrap_or(StoreError::Database(sqlx::Error::PoolTimedOut)));
            };
            if remaining.is_zero() {
                return Err(last_err.unwrap_or(StoreError::Database(sqlx::Error::PoolTimedOut)));
            }
            match tokio::time::timeout(remaining, Self::connect_inner(url, opts.clone(), None))
                .await
            {
                Ok(Ok(db)) => return Ok(db),
                Ok(Err(err)) => {
                    if is_permanent_connect_error(&err) || Instant::now() >= deadline {
                        return Err(err);
                    }
                    let sleep_for = backoff.min(deadline.saturating_duration_since(Instant::now()));
                    if sleep_for.is_zero() {
                        return Err(err);
                    }
                    last_err = Some(err);
                    tokio::time::sleep(sleep_for).await;
                    backoff = (backoff * 2).min(Duration::from_secs(2));
                }
                Err(_) => {
                    return Err(last_err.unwrap_or(StoreError::Database(sqlx::Error::PoolTimedOut)));
                }
            }
        }
    }

    async fn connect_inner(
        url: &str,
        opts: DbOptions,
        test_cleanup: Option<Arc<test_db::TestSchemaGuard>>,
    ) -> Result<Self, StoreError> {
        let connect_opts = parse_connect_options(url, opts.schema.as_deref())?;
        let pool = PgPoolOptions::new()
            .max_connections(opts.max_connections.clamp(1, 100))
            .min_connections(0)
            .acquire_timeout(opts.acquire_timeout)
            .idle_timeout(Some(opts.idle_timeout))
            .test_before_acquire(true)
            .connect_with(connect_opts)
            .await?;
        run_migrations(&pool, MIGRATIONS).await?;
        Ok(Self {
            pool,
            _test_cleanup: test_cleanup,
        })
    }

    /// Creates a lazy, unmigrated pool for testing unreachable-database behavior.
    #[doc(hidden)]
    pub fn connect_lazy_unmigrated(
        url: &str,
        acquire_timeout: Duration,
    ) -> Result<Self, StoreError> {
        let connect_opts = parse_connect_options(url, None)?;
        let pool = PgPoolOptions::new()
            .max_connections(1)
            .min_connections(0)
            .acquire_timeout(acquire_timeout)
            .connect_lazy_with(connect_opts);
        Ok(Self {
            pool,
            _test_cleanup: None,
        })
    }

    /// Creates an isolated temporary schema in the test PostgreSQL database and
    /// returns a migrated pool scoped to it. The schema is dropped on drop.
    #[doc(hidden)]
    pub async fn connect_test() -> Self {
        let schema = test_db::TestSchema::create().await;
        schema
            .connect()
            .await
            .unwrap_or_else(|e| panic!("failed to connect to test schema: {e}"))
    }

    /// Checks database connectivity with a fast query.
    pub async fn ping(&self) -> Result<(), StoreError> {
        sqlx::query_scalar::<_, i32>("SELECT 1")
            .fetch_one(&self.pool)
            .await?;
        Ok(())
    }

    /// Closes all pooled connections cleanly.
    pub async fn close(&self) {
        self.pool.close().await;
    }

    pub fn pool(&self) -> &PgPool {
        &self.pool
    }
}

/// Printers registered with the API, stored in PostgreSQL.
pub struct PrinterStore {
    db: Db,
}

impl PrinterStore {
    /// A registry over a connection pool shared with the auth store.
    pub fn from_db(db: Db) -> Self {
        Self { db }
    }

    /// Checks database connectivity.
    pub async fn ping(&self) -> Result<(), StoreError> {
        self.db.ping().await
    }

    pub async fn list(&self) -> Result<Vec<StoredPrinter>, StoreError> {
        let rows =
            sqlx::query("SELECT name, kind, host, username, password FROM printers ORDER BY name")
                .fetch_all(self.db.pool())
                .await?;
        rows.iter().map(row_to_printer).collect()
    }

    pub async fn get(&self, name: &str) -> Result<Option<StoredPrinter>, StoreError> {
        let row = sqlx::query(
            "SELECT name, kind, host, username, password FROM printers WHERE name = $1",
        )
        .bind(name)
        .fetch_optional(self.db.pool())
        .await?;
        row.as_ref().map(row_to_printer).transpose()
    }

    pub async fn insert(&self, printer: StoredPrinter) -> Result<(), StoreError> {
        let result = sqlx::query(
            "INSERT INTO printers (name, kind, host, username, password) VALUES ($1, $2, $3, $4, $5)",
        )
        .bind(&printer.name)
        .bind(printer.kind.as_str())
        .bind(&printer.host)
        .bind(&printer.username)
        .bind(&printer.password)
        .execute(self.db.pool())
        .await;

        match result {
            Ok(_) => Ok(()),
            Err(err) if is_unique_violation(&err) => Err(StoreError::Duplicate(printer.name)),
            Err(err) => Err(err.into()),
        }
    }

    /// Returns `Ok(false)` when no printer has that name.
    pub async fn remove(&self, name: &str) -> Result<bool, StoreError> {
        let res = sqlx::query("DELETE FROM printers WHERE name = $1")
            .bind(name)
            .execute(self.db.pool())
            .await?;
        Ok(res.rows_affected() > 0)
    }
}

fn row_to_printer(row: &sqlx::postgres::PgRow) -> Result<StoredPrinter, StoreError> {
    let kind: String = row.try_get(1)?;
    let kind = kind
        .parse::<PrinterKind>()
        .map_err(|err| sqlx::Error::ColumnDecode {
            index: "kind".to_owned(),
            source: Box::new(err),
        })?;

    Ok(StoredPrinter {
        name: row.try_get(0)?,
        kind,
        host: row.try_get(2)?,
        username: row.try_get(3)?,
        password: row.try_get(4)?,
    })
}

/// Isolated per-test PostgreSQL schema management.
#[doc(hidden)]
pub mod test_db {
    use std::sync::{Arc, OnceLock, mpsc};
    use std::time::Duration;

    use sqlx::postgres::{PgConnectOptions, PgPoolOptions};
    use sqlx::{Connection, Executor, PgConnection, PgPool};

    use super::{Db, DbOptions, StoreError, parse_connect_options};

    fn default_test_database_url() -> String {
        let pw = std::env::var("STARSTAR_DB_PASSWORD")
            .ok()
            .filter(|s| !s.is_empty())
            .unwrap_or_else(|| ["starstar", "dev"].join("-"));
        let mut url = url::Url::parse("postgres://starstar@127.0.0.1:54329/starstar")
            .expect("valid default test database URL");
        url.set_password(Some(&pw)).expect("set test DB password");
        url.to_string()
    }

    /// Returns `STARSTAR_TEST_DATABASE_URL` or the local Compose dev database URL.
    pub fn test_database_url() -> String {
        std::env::var("STARSTAR_TEST_DATABASE_URL")
            .ok()
            .map(|s| s.trim().to_owned())
            .filter(|s| !s.is_empty())
            .unwrap_or_else(default_test_database_url)
    }

    struct CleanupMsg {
        url: String,
        schema: String,
        done: mpsc::SyncSender<()>,
    }

    fn cleanup_sender() -> &'static mpsc::Sender<CleanupMsg> {
        static SENDER: OnceLock<mpsc::Sender<CleanupMsg>> = OnceLock::new();
        SENDER.get_or_init(|| {
            let (tx, rx) = mpsc::channel::<CleanupMsg>();
            std::thread::Builder::new()
                .name("starstar-test-schema-cleanup".to_owned())
                .spawn(move || {
                    let rt = tokio::runtime::Builder::new_current_thread()
                        .enable_all()
                        .build()
                        .expect("cleanup tokio runtime");
                    let mut cached_conn: Option<(String, PgConnection)> = None;
                    while let Ok(msg) = rx.recv() {
                        rt.block_on(async {
                            let sql = format!(r#"DROP SCHEMA IF EXISTS "{}" CASCADE"#, msg.schema);
                            let step_timeout = Duration::from_secs(3);
                            if let Some((cached_url, mut conn)) = cached_conn.take()
                                && cached_url == msg.url
                                && matches!(
                                    tokio::time::timeout(step_timeout, conn.execute(sql.as_str()))
                                        .await,
                                    Ok(Ok(_))
                                )
                            {
                                cached_conn = Some((cached_url, conn));
                                return;
                            }
                            if let Ok(opts) = parse_connect_options(&msg.url, None)
                                && let Ok(Ok(mut conn)) = tokio::time::timeout(
                                    step_timeout,
                                    PgConnection::connect_with(&opts),
                                )
                                .await
                                && matches!(
                                    tokio::time::timeout(step_timeout, conn.execute(sql.as_str()))
                                        .await,
                                    Ok(Ok(_))
                                )
                            {
                                cached_conn = Some((msg.url, conn));
                            }
                        });
                        let _ = msg.done.send(());
                    }
                })
                .expect("spawn test schema cleanup thread");
            tx
        })
    }

    pub(crate) struct TestSchemaGuard {
        url: String,
        schema: String,
    }

    impl Drop for TestSchemaGuard {
        fn drop(&mut self) {
            let (done_tx, done_rx) = mpsc::sync_channel(1);
            if cleanup_sender()
                .send(CleanupMsg {
                    url: self.url.clone(),
                    schema: self.schema.clone(),
                    done: done_tx,
                })
                .is_ok()
            {
                let _ = done_rx.recv_timeout(Duration::from_secs(10));
            }
        }
    }

    /// A unique PostgreSQL schema that is dropped automatically when all clones
    /// of its guard and connected [`Db`] instances are dropped.
    #[derive(Clone)]
    pub struct TestSchema {
        url: String,
        schema: String,
        guard: Arc<TestSchemaGuard>,
    }

    impl TestSchema {
        /// Creates a fresh isolated schema on the test PostgreSQL instance.
        pub async fn create() -> Self {
            let url = test_database_url();
            let mut bytes = [0u8; 8];
            getrandom::fill(&mut bytes).expect("OS RNG for test schema name");
            let hex: String = bytes.iter().map(|b| format!("{b:02x}")).collect();
            let schema = format!("starstar_test_{hex}");

            let opts: PgConnectOptions = parse_connect_options(&url, None)
                .unwrap_or_else(|e| panic!("invalid test database URL: {e}"));
            let mut conn = PgConnection::connect_with(&opts).await.unwrap_or_else(|e| {
                panic!(
                    "could not connect to PostgreSQL test database (set STARSTAR_TEST_DATABASE_URL or start `podman compose up -d db`): {e}"
                )
            });
            let sql = format!(r#"CREATE SCHEMA "{schema}""#);
            conn.execute(sql.as_str())
                .await
                .unwrap_or_else(|e| panic!("could not create test schema {schema}: {e}"));
            let _ = conn.close().await;

            let guard = Arc::new(TestSchemaGuard {
                url: url.clone(),
                schema: schema.clone(),
            });
            Self { url, schema, guard }
        }

        pub fn name(&self) -> &str {
            &self.schema
        }

        pub fn url(&self) -> &str {
            &self.url
        }

        /// Opens a migrated [`Db`] scoped to this schema (default `max_connections = 4`).
        pub async fn connect(&self) -> Result<Db, StoreError> {
            self.connect_with_max_connections(4).await
        }

        /// Opens a migrated [`Db`] scoped to this schema with an explicit pool size.
        pub async fn connect_with_max_connections(&self, max: u32) -> Result<Db, StoreError> {
            Db::connect_inner(
                &self.url,
                DbOptions {
                    max_connections: max,
                    schema: Some(self.schema.clone()),
                    ..Default::default()
                },
                Some(Arc::clone(&self.guard)),
            )
            .await
        }

        /// Opens an unmigrated pool scoped to this schema for migration tests.
        pub async fn connect_unmigrated(&self) -> Result<PgPool, StoreError> {
            let opts = parse_connect_options(&self.url, Some(&self.schema))?;
            Ok(PgPoolOptions::new()
                .max_connections(2)
                .min_connections(0)
                .acquire_timeout(Duration::from_secs(5))
                .connect_with(opts)
                .await?)
        }
    }
}

