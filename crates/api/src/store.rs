    #[tokio::test]
    async fn failed_migration_rolls_back_cleanly() {
        let schema = TestSchema::create().await;
        let pool = schema.connect_unmigrated().await.unwrap();
        let bad = [
            MIGRATIONS[0].sql,
            "CREATE TABLE partial_should_rollback (id INT); INSERT INTO schema_migrations (version, name, applied_at) VALUES (2, 'conflict', 0);",
        ];
        let migrations = [
            Migration {
                version: 1,
                name: "ok",
                sql: bad[0],
            },
            Migration {
                version: 2,
                name: "broken",
                sql: bad[1],
            },
        ];
        assert!(run_migrations(&pool, &migrations).await.is_err());

        for table in ["schema_migrations", "printers", "partial_should_rollback"] {
            let exists: bool = sqlx::query_scalar(
                "SELECT EXISTS (SELECT 1 FROM information_schema.tables WHERE table_schema = current_schema() AND table_name = $1)",
            )
            .bind(table)
            .fetch_one(&pool)
            .await
            .unwrap();
            assert!(!exists, "table {table} should have rolled back");
        }

        // Now apply v1 cleanly, then fail on v2: v1 stays and v2 rolls back completely.
        run_migrations(&pool, &migrations[..1]).await.unwrap();
        assert!(run_migrations(&pool, &migrations).await.is_err());

        let partial_exists: bool = sqlx::query_scalar(
            "SELECT EXISTS (SELECT 1 FROM information_schema.tables WHERE table_schema = current_schema() AND table_name = 'partial_should_rollback')",
        )
        .fetch_one(&pool)
        .await
        .unwrap();
        assert!(!partial_exists);

        let versions: Vec<i32> =
            sqlx::query_scalar("SELECT version FROM schema_migrations ORDER BY version")
                .fetch_all(&pool)
                .await
                .unwrap();
        assert_eq!(versions, vec![1]);
    }

